REGIONS: list[Region] = [Region(c, n, d, p) for c, n, d, p in _RAW]
BY_CODE: dict[str, Region] = {r.code: r for r in REGIONS}
_COMPILED = [(r, [re.compile(p) for p in r.patterns]) for r in REGIONS]

_DISTRICT_PATTERNS = [
    ("СФО", r"(?<![а-я])сибир|\bсфо\b"),
    ("УФО", r"(?<![а-я])урал(?!ьск)|\bуфо\b"),
    ("ДФО", r"дальн\w*\s*восток|дальневосточ|\bдфо\b"),
    ("ПФО", r"поволж|приволж|\bпфо\b"),
    ("СЗФО", r"северо-запад|\bсзфо\b"),
    ("ЦФО", r"центральн\w* (россии|федеральн|округ)|\bцфо\b"),
    ("СКФО", r"северн\w* кавказ|северо-кавказ|\bскфо\b"),
    ("ЮФО", r"южн\w* (россии|федеральн|округ)|\bюфо\b|\bюг\b россии"),
]


def normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


def find_regions(text: str) -> list[Region]:
    """Все субъекты, упомянутые в тексте, в порядке справочника, без повторов."""
    t = normalize(text)
    # «обл. Ивановская», «край Алтайский» — в адресах ЕИС слово «область» бывает впереди
    t = re.sub(r"\b(обл(?:асть)?|край|респ(?:ублика)?)\.?\s+([а-я-]+)", r"\2 \1 \2", t)
    found: list[Region] = []
    for region, patterns in _COMPILED:
        if any(p.search(t) for p in patterns):
            found.append(region)
    # «МО» и «ЛО» — только заглавными (иначе ловили бы обычные слова)
    for code, abbr in (("50", "МО"), ("47", "ЛО")):
        if re.search(rf"(?<![А-Яа-яЁё]){abbr}(?![А-Яа-яЁё])", text) and BY_CODE[code] not in found:
            found.append(BY_CODE[code])
    return found


def detect_region(text: str | None) -> Region | None:
    if not text:
        return None
    hits = find_regions(text)
    return hits[0] if hits else None


def find_districts(text: str) -> list[str]:
    t = normalize(text)
    return [code for code, pattern in _DISTRICT_PATTERNS if re.search(pattern, t)]


def regions_of_district(district: str) -> list[Region]:
    return [r for r in REGIONS if r.district == district]


def region_from_inn(inn: str | None) -> Region | None:
    """Первые две цифры ИНН — код налогового органа, обычно совпадает с регионом."""
    if inn and len(inn) >= 2:
        return BY_CODE.get(inn[:2])
    return None
