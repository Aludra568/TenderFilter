def _norm(code: str) -> str:
    return code.strip().rstrip(".")


def match_okved_okpd(okveds: list[str], okpd_codes: list[str]) -> tuple[float, str | None, str | None]:
    """Лучшее совпадение между ОКВЭД компании и ОКПД закупки.

    Возвращает (балл 0–1, код ОКВЭД, код ОКПД) лучшей пары.
    """
    best: tuple[float, str | None, str | None] = (0.0, None, None)
    for raw_okved in okveds:
        okved = _norm(raw_okved)
        is_trade = okved.startswith(("46.", "47."))
        for raw_okpd in okpd_codes:
            okpd = _norm(raw_okpd)
            score = 0.0
            if is_trade:
                prefixes = TRADE_MAP.get(okved[:5]) or TRADE_MAP.get(okved[:4]) or []
                if "*" in prefixes:
                    score = 0.6
                elif any(okpd.startswith(p) for p in prefixes):
                    score = 0.9
            else:
                if okpd[:5] == okved[:5]:
                    score = 0.95
                elif okpd[:4] == okved[:4]:
                    score = 0.85
                elif okpd[:2] == okved[:2]:
                    score = 0.6
            if score > best[0]:
                best = (score, okved, okpd)
    return best
